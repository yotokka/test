/** Пересобирает docs/catalog/coverage.md из каталога техники (npm run docs:coverage). */
import { writeFileSync } from 'node:fs';
import { CAT_RU, CATALOG, coverageTable, OPERATOR_RU, VARIANTS } from '../../src/data/reference/catalog';
const t = coverageTable();
const L: string[] = [];
L.push('| Категория | ' + t.decades.map((d) => (d === 1940 ? '≤1940-е' : `${d}-е`)).join(' | ') + ' | без даты |');
L.push('|---|' + t.decades.map(() => '---').join('|') + '|---|');
for (const c of t.cats) L.push(`| ${CAT_RU[c]} | ` + t.decades.map((d) => { const x = t.byCat[c][d]; return x.variants ? `${x.variants} (${x.withOperator})` : '·'; }).join(' | ') + ` | ${t.undated[c] || '·'} |`);
L.push('');
L.push('| Страна происхождения | ' + t.cats.map((c) => CAT_RU[c]).join(' | ') + ' |');
L.push('|---|' + t.cats.map(() => '---').join('|') + '|');
for (const o of Object.keys(t.byCountry)) L.push(`| ${OPERATOR_RU[o] ?? o} | ` + t.cats.map((c) => t.byCountry[o][c] || '·').join(' | ') + ' |');
L.push('');
L.push('| Семейство | Категория | Происхождение | Модификация | Этапы | Эксплуатант и период |');
L.push('|---|---|---|---|---|---|');
for (const f of CATALOG) for (const v of f.variants) L.push(`| ${f.name} | ${CAT_RU[f.category]} | ${OPERATOR_RU[f.origin] ?? f.origin} | ${v.name} | ${v.milestones.map((m) => `${m.kind} ${m.date}`).join('; ') || 'не установлены'} | ${v.operators.map((o) => `${OPERATOR_RU[o.operator] ?? o.operator}: ${o.from ?? '?'}–${o.to ?? (o.confirmedUntil ? 'подтв. до ' + o.confirmedUntil : '?')}`).join('; ') || 'не установлен'} |`);


const HEAD = `# Каталог техники: покрытие

Каталог хранит семейство, модификацию, страну происхождения и эксплуатантов раздельно. Принадлежность стране — только период эксплуатации с источником, отметкой проверки и описанием неопределённости. Заказано, поставлено и находится в строю — разные поля; неизвестное — пусто, а не ноль. Наличие системы в каталоге не означает, что она была у какой-либо страны.

Состояние на 26.09.2026: семейств — **${CATALOG.length}**, модификаций — **${VARIANTS.length}**, категорий — 8. Все сведения сверены по поисковой выдаче: страницы источников из среды сборки не открывались (статус \`search-index\`).

Как читать таблицу: число модификаций по десятилетию первого известного этапа (разработка, испытание или служба); в скобках — сколько из них имеют период эксплуатации. «·» — в каталоге нет записей, а не «такой техники не было».

`;
const TAIL = `
## Известные пробелы

- Нет советских и российских бомбардировщиков, авиационных ракет и беспилотников: в выдаче официальных и музейных страниц с датами не нашлось.
- Нет техники КНР, Индии, Израиля вне ракет.
- Нет экспортных эксплуатантов: подходящий реестр (SIPRI Arms Transfers Database) в этой сборке недоступен.
- У многих периодов известно только начало эксплуатации. Такой период не подтверждает эксплуатацию на поздние даты: в редакторе сценариев строгий режим доступности её не засчитает.
- Численность известна только для U-2 («инвентарь 33», без даты справки).

## Как расширять

1. Найдите официальную, музейную или производственную страницу с датой этапа или периодом эксплуатации.
2. Добавьте источник в \`src/data/reference/sources.ts\` (ссылка — только из выдачи или открытой страницы, не собранная вручную).
3. Добавьте семейство или модификацию в \`src/data/reference/catalogData.ts\`. Не заполняйте пробелы по памяти: пустое поле лучше выдуманного.
4. Запустите \`npm test\`: проверяются существование источников, формат дат, раздельные счётчики и объяснение пустых полей.
5. Пересоберите этот документ: \`npm run docs:coverage\`.
`;
writeFileSync('docs/catalog/coverage.md', HEAD + L.join('\n') + '\n' + TAIL);
console.log(`docs/catalog/coverage.md: ${CATALOG.length} семейств, ${VARIANTS.length} модификаций`);
