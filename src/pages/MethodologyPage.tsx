function Toc() {
  const { setOpen } = useAside();
  return (
    <nav aria-label="Содержание страницы" className="fade-in">
      <ol className="toc">
        {SECTIONS.map((s) => (
          <li key={s.id}>
            <a
              href="#/methodology"
              onClick={(e) => {
                e.preventDefault();
                setOpen(false);
                const el = document.getElementById(s.id);
                el?.scrollIntoView();
                el?.focus({ preventScroll: true });
              }}
            >
              {s.title}
            </a>
          </li>
        ))}
      </ol>
    </nav>
  );
}
